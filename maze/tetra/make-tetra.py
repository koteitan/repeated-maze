#!/usr/bin/env python3
"""make-tetra.py — Generate tetra-M-4d.hs, a 4-register Minsky machine whose
register b ends as a power tower of 2s.

Registers (a, b, c, d) get the Gödel primes 2, 3, 5, 7 in nd-to-2d.py.
The machine starts at (0, 1, 0, 0) (the nd-to-2d convention r_1 = 1), so b
is already 1 and needs no setup.

    pc 0: a := A, d := M-1
    pass (pc 2-4):  b := b * 2^a, a := 0      (c is the temporary)
    pc 5: d = 0 -> HALT, else d := d-1
    pc 6: a := b, b := 1, next pass

Each pass computes b := 2^a, so after M passes
    b = 2^2^...^2^A     (M twos).
For A = 2: M = 3 gives b = 65536, M = 4 gives b = 2^65536.

Usage: python3 make-tetra.py M [A] > tetra-M-4d.hs   (A defaults to 2)
"""
import sys

USAGE = "Usage: make-tetra.py M [A]   (M >= 1, A >= 1, default A = 2)"


def main() -> None:
    if len(sys.argv) not in (2, 3) or not all(s.isdigit() for s in sys.argv[1:]):
        print(USAGE, file=sys.stderr)
        sys.exit(1)
    m = int(sys.argv[1])
    a0 = int(sys.argv[2]) if len(sys.argv) == 3 else 2
    if a0 < 1 or m < 1:
        print(USAGE, file=sys.stderr)
        sys.exit(1)

    out = [
        f"-- tetra-{m}-4d.hs: power tower of 2s (4-register Minsky). M={m}, A={a0}",
        f"-- Start: (0, 1, 0, 0, 0). Goal: pc 1 with b = {'2^' * m}{a0}.",
        "-- Generated by make-tetra.py.  Feed through nd-to-2d.py --fuse -> hs2maze.py.",
        "",
        "tetra :: (Int, Int, Int, Int, Int) -> (Int, Int, Int, Int, Int)",
        "",
        f"-- Setup (pc=0): a := {a0}, d := {m - 1} (remaining passes)",
        f"tetra (a, b, c, d,    0) = tetra (a+{a0}, b, c, d+{m - 1},    2)"
        if m > 1 else
        f"tetra (a, b, c, d,    0) = tetra (a+{a0}, b, c, d,    2)",
        "",
        "-- Loop (pc=2): a=0 -> end of pass, else DEC a and double b",
        "tetra (0, b, c, d,    2) = tetra (  0,   b,   c,   d,    5)",
        "tetra (a, b, c, d,    2) = tetra (a-1,   b,   c,   d,    3)",
        "",
        "-- Double (pc=3): move b to c, two c per b",
        "tetra (a, 0, c, d,    3) = tetra (  a,   0,   c,   d,    4)",
        "tetra (a, b, c, d,    3) = tetra (  a, b-1, c+2,   d,    3)",
        "",
        "-- Transfer (pc=4): move c back to b",
        "tetra (a, b, 0, d,    4) = tetra (  a,   b,   0,   d,    2)",
        "tetra (a, b, c, d,    4) = tetra (  a, b+1, c-1,   d,    4)",
        "",
        "-- Pass count (pc=5): d=0 -> HALT, else DEC d",
        "tetra (a, b, c, 0,    5) = (  a,   b,   c,   0,    1)",
        "tetra (a, b, c, d,    5) = tetra (  a,   b,   c, d-1,    6)",
        "",
        "-- Next pass (pc=6): move b to a, then b := 1",
        "tetra (a, 0, c, d,    6) = tetra (  a,   1,   c,   d,    2)",
        "tetra (a, b, c, d,    6) = tetra (a+1, b-1,   c,   d,    6)",
    ]
    print("\n".join(out))


if __name__ == "__main__":
    main()
