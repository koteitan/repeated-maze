#!/usr/bin/env python3
"""make-exmd.py — Generate exmd<M>-<K>.hs, the extended Minsky doubling
machine: a 2-register machine that multiplies a value by M, K times.

Cycle c (c = 0, 1, ..., K-1) moves the value from one register to the
other, M units per unit:
    c even:  y -> x   (y-1, then M times x+1, until y = 0)
    c odd:   x -> y   (x-1, then M times y+1, until x = 0)
Unlike md<k> (make-minsky-doubling.py), nothing is moved back, so a cycle
needs only M + 2 rules.  After K cycles the value is M^K; it is then
drained to 0 and the machine halts at (0, 0, 1).

    pc 0:  y := 1
    cycle c at pc S = 2 + c(M+1):  S = zero test + DEC, S+1..S+M = INC
    drain at pc D = 2 + K(M+1)

Usage: python3 make-exmd.py M K > exmdM-K.hs
"""
import sys

USAGE = "Usage: make-exmd.py M K   (M >= 2, K >= 1)"


def main() -> None:
    if len(sys.argv) != 3 or not all(s.isdigit() for s in sys.argv[1:]):
        print(USAGE, file=sys.stderr)
        sys.exit(1)
    m, k = int(sys.argv[1]), int(sys.argv[2])
    if m < 2 or k < 1:
        print(USAGE, file=sys.stderr)
        sys.exit(1)

    out = [
        f"-- exmd{m}-{k}.hs: extended Minsky doubling (value x{m}, {k} cycles)",
        f"-- Start: (0, 0, 0). Goal: (0, 0, 1). The value reaches {m}^{k} = {m ** k}.",
        "-- Generated by make-exmd.py.  Feed through hs2maze.py to obtain the maze.",
        "",
        "exmd :: (Int, Int, Int) -> (Int, Int, Int)",
        "",
        "-- Phase 0 (pc=0): y := 1",
        "exmd (x, y,    0) = exmd (  x, y+1,    2)",
    ]
    s = 2
    for c in range(k):
        nxt = s + m + 1
        out.append("")
        if c % 2 == 0:
            out.append(f"-- Cycle {c} (pc={s}): y -> x, x{m}")
            out.append(f"exmd (x, 0, {s:4d}) = exmd (  x,   0, {nxt:4d})")
            out.append(f"exmd (x, y, {s:4d}) = exmd (  x, y-1, {s + 1:4d})")
            for i in range(m):
                dst = s + 2 + i if i + 1 < m else s
                out.append(f"exmd (x, y, {s + 1 + i:4d}) = exmd (x+1,   y, {dst:4d})")
        else:
            out.append(f"-- Cycle {c} (pc={s}): x -> y, x{m}")
            out.append(f"exmd (0, y, {s:4d}) = exmd (  0,   y, {nxt:4d})")
            out.append(f"exmd (x, y, {s:4d}) = exmd (x-1,   y, {s + 1:4d})")
            for i in range(m):
                dst = s + 2 + i if i + 1 < m else s
                out.append(f"exmd (x, y, {s + 1 + i:4d}) = exmd (  x, y+1, {dst:4d})")
        s = nxt
    out.append("")
    if k % 2 == 1:
        out.append(f"-- Drain (pc={s}): DEC x to 0, then HALT")
        out.append(f"exmd (0, y, {s:4d}) = (  0,   y,    1)")
        out.append(f"exmd (x, y, {s:4d}) = exmd (x-1,   y, {s:4d})")
    else:
        out.append(f"-- Drain (pc={s}): DEC y to 0, then HALT")
        out.append(f"exmd (x, 0, {s:4d}) = (  x,   0,    1)")
        out.append(f"exmd (x, y, {s:4d}) = exmd (  x, y-1, {s:4d})")
    print("\n".join(out))


if __name__ == "__main__":
    main()
